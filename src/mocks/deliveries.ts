export type DeliveryStatus =
  | 'Heading to Terminal'
  | 'Waiting'
  | 'Loading'
  | 'In Transit'
  | 'At Customer'
  | 'Delivering'
  | 'Completed';

export interface DeliveryDocument {
  name: string;
  value: string;
  status: 'Uploaded' | 'Pending' | 'Exception';
}

export interface DeliveryTimeline {
  time: string;
  label: string;
  state: 'completed' | 'current' | 'upcoming' | 'delayed';
}

export interface Delivery {
  id: string;
  order: string;
  customer: string;
  route: string;
  product: string;
  volume: string;
  driver: string;
  driverId: string | null;
  truck: string;
  status: DeliveryStatus;
  window: string;
  eta: string;
  location: string;
  exception?: string;
  bol: string;
  pod: 'Signed' | 'Pending' | 'Exception';
  signature: string;
  deliveryTicket: string;
  notes: string;
  documents: DeliveryDocument[];
  timeline: DeliveryTimeline[];
}

