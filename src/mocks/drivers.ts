export type DriverStatus =
  | 'Available'
  | 'Assigned'
  | 'Loading'
  | 'In Transit'
  | 'Delivering'
  | 'Break'
  | 'Off Duty';

export type ExceptionKind = 'Delayed' | 'Driver Issue' | 'Truck Issue' | 'Terminal Delay';

export interface DriverException {
  kind: ExceptionKind;
  detail: string;
}

export interface TruckChange {
  from: string;
  at: string;
}

export interface ScheduleEvent {
  time: string;
  label: string;
  state: 'completed' | 'current' | 'upcoming' | 'delayed';
}

export interface DeliveryRecord {
  date: string;
  order: string;
  route: string;
  truck: string;
  product: string;
  volume: string;
  deliveryTime: string;
  status: 'Completed' | 'Delayed';
  statusDetail?: string;
  bol: string;
  pod: 'Signed' | 'Pending' | 'Exception';
  signature: string;
  deliveredQty: string;
  notes: string;
  exception?: string;
}

export interface Driver {
  id: string;
  name: string;
  initials: string;
  status: DriverStatus;
  exceptions: DriverException[];
  truck: string | null;
  truckChangedFrom?: TruckChange;
  currentAssignment: string | null;
  product: string;
  volume: string;
  route: string;
  location: string;
  shift: string;
  todayRuns: string;
  nextAssignment: string;
  eta: string | null;
  phone: string;
  schedule: ScheduleEvent[];
  history: DeliveryRecord[];
}

