export type TruckStatus =
  | 'Available'
  | 'Assigned'
  | 'Heading to Terminal'
  | 'Loading'
  | 'In Transit'
  | 'At Customer'
  | 'Maintenance'
  | 'Out of Service';

export interface ServiceRecord {
  date: string;
  type: string;
  mileage: string;
  notes: string;
}

export interface Compartment {
  capacity: string;
  product: string;
  volume: string;
  state: 'Full' | 'Partial' | 'Empty';
}

export interface TruckScheduleEvent {
  time: string;
  label: string;
  state: 'completed' | 'current' | 'upcoming' | 'conflict' | 'delayed';
}

export interface Truck {
  id: string;
  plate: string;
  make: string;
  model: string;
  type: string;
  capacity: string;
  compartments: number;
  product: string;
  adrClass: string;
  year: string;
  mileage: string;
  base: string;
  status: TruckStatus;
  currentDriver: string | null;
  currentDriverId: string | null;
  currentAssignment: string | null;
  orderId: string | null;
  location: string;
  nextService: string;
  lastInspection: string;
  serviceHistory: ServiceRecord[];
  compartmentsDetail?: Compartment[];
  schedule?: TruckScheduleEvent[];
  nextAssignment?: string | null;
  notes?: string;
  /** Linked trailer id — enables truck + trailer mix-and-match. */
  trailerId?: string | null;
}

export interface Trailer {
  id: string;
  plate: string;
  type: string;
  capacity: string;
  compartments: number;
  product: string;
  base: string;
  status: 'Available' | 'In Use' | 'Maintenance';
}

